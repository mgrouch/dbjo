CREATE FUNCTION PARTITION_ID(key VARCHAR(8000), parts INTEGER)
  RETURNS INTEGER
  LANGUAGE SQL
  DETERMINISTIC
  BEGIN ATOMIC
    DECLARE h BIGINT;
    DECLARE i INTEGER;
    DECLARE len INTEGER;
    DECLARE b INTEGER;
    IF key IS NULL OR parts IS NULL OR parts <= 0 THEN
      RETURN NULL;
    END IF;
    SET h = 2166136261;
    SET i = 1;
    SET len = OCTET_LENGTH(key);
    WHILE i <= len DO
      SET b = ASCII(SUBSTRING(key, i, 1));
      SET h = BITXOR(h, b);
      SET h = MOD(h * 16777619, 4294967296);
      SET i = i + 1;
    END WHILE;
    RETURN CAST(MOD(h, parts) AS INTEGER);
  END;

DROP TABLE IF EXISTS purchase;
DROP TABLE IF EXISTS product;
DROP TABLE IF EXISTS client;

CREATE TABLE client (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email    VARCHAR(255) NOT NULL UNIQUE,
  name     VARCHAR(200) NOT NULL,
  version  INTEGER NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE product (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku       VARCHAR(64) NOT NULL UNIQUE,
  title     VARCHAR(255) NOT NULL,
  price_cents INTEGER NOT NULL CHECK (price_cents >= 0)
);

CREATE TABLE purchase (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id   BIGINT NOT NULL,
  product_id  BIGINT NOT NULL,
  qty         INTEGER NOT NULL CHECK (qty > 0),
  ordered_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_purchase_client FOREIGN KEY (client_id) REFERENCES client(id),
  CONSTRAINT fk_purchase_product FOREIGN KEY (product_id) REFERENCES product(id)
);
